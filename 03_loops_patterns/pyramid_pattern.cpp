#include<iostream>
using namespace std;
int main(){
    int d;
    char b;
    
    cout<<"Enter Pyramid line :  ";
    cin>>d;
    cout<<"Enter Pyramid Symbol : ";
    cin>>b;

for(int c=1;c<=d;c++){
    for(int j=1;j<=c;j++){
      cout<<b;  }
   
      cout<<endl;  }

return 0; } 